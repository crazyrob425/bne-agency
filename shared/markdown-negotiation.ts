export function htmlToMarkdown(html: string, pageUrl?: string): string {
  const titleMatch = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  const rawTitle = titleMatch ? stripHtml(titleMatch[1]) : '';

  const descMatch =
    html.match(/<meta[^>]*name=["']description["'][^>]*content=["']([\s\S]*?)["']/i) ||
    html.match(/<meta[^>]*content=["']([\s\S]*?)["'][^>]*name=["']description["']/i);
  const metaDescription = descMatch ? stripHtml(descMatch[1]) : '';

  let cleanHtml = html
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<noscript[\s\S]*?<\/noscript>/gi, '')
    .replace(/<svg[\s\S]*?<\/svg>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '');

  const mainMatch =
    cleanHtml.match(/<main[^>]*>([\s\S]*?)<\/main>/i) ||
    cleanHtml.match(/<article[^>]*>([\s\S]*?)<\/article>/i) ||
    cleanHtml.match(/<body[^>]*>([\s\S]*?)<\/body>/i);

  const bodyContent = mainMatch ? mainMatch[1] : cleanHtml;

  let md = bodyContent
    .replace(/<h1[^>]*>([\s\S]*?)<\/h1>/gi, (_, text) => `\n\n# ${stripHtml(text)}\n\n`)
    .replace(/<h2[^>]*>([\s\S]*?)<\/h2>/gi, (_, text) => `\n\n## ${stripHtml(text)}\n\n`)
    .replace(/<h3[^>]*>([\s\S]*?)<\/h3>/gi, (_, text) => `\n\n### ${stripHtml(text)}\n\n`)
    .replace(/<h4[^>]*>([\s\S]*?)<\/h4>/gi, (_, text) => `\n\n#### ${stripHtml(text)}\n\n`)
    .replace(/<h5[^>]*>([\s\S]*?)<\/h5>/gi, (_, text) => `\n\n##### ${stripHtml(text)}\n\n`)
    .replace(/<h6[^>]*>([\s\S]*?)<\/h6>/gi, (_, text) => `\n\n###### ${stripHtml(text)}\n\n`);

  md = md.replace(/<a[^>]*href=["']([^"']*)["'][^>]*>([\s\S]*?)<\/a>/gi, (_, href, text) => {
    const cleanText = stripHtml(text);
    if (!cleanText) return '';
    return ` [${cleanText}](${href}) `;
  });

  md = md.replace(/<li[^>]*>([\s\S]*?)<\/li>/gi, (_, text) => `\n- ${stripHtml(text)}`);

  md = md
    .replace(/<p[^>]*>([\s\S]*?)<\/p>/gi, (_, text) => `\n\n${stripHtml(text)}\n\n`)
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<tr[^>]*>([\s\S]*?)<\/tr>/gi, (_, text) => `\n${stripHtml(text)}`)
    .replace(/<div[^>]*>/gi, '\n')
    .replace(/<\/div>/gi, '\n');

  md = md.replace(/<[^>]+>/g, ' ');

  md = md
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");

  const lines = md
    .split('\n')
    .map((line) => line.replace(/[ \t]+/g, ' ').trim())
    .filter((line, i, arr) => line !== '' || (i > 0 && arr[i - 1] !== ''));

  md = lines.join('\n');

  const headerParts: string[] = [];
  if (rawTitle) {
    headerParts.push(`# ${rawTitle}`);
  }
  if (metaDescription) {
    headerParts.push(`> ${metaDescription}`);
  }
  if (pageUrl) {
    headerParts.push(`*Source: ${pageUrl}*`);
  }

  const documentHeader = headerParts.length > 0 ? headerParts.join('\n\n') + '\n\n---\n\n' : '';

  return (documentHeader + md).trim() + '\n';
}

export function estimateTokenCount(text: string): number {
  return Math.ceil(text.length / 4);
}
